CREATE TABLE books (
  book_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR2(200) NOT NULL,
  author VARCHAR2(150) NOT NULL,
  isbn VARCHAR2(30) UNIQUE,
  total_copies NUMBER(5) DEFAULT 1 NOT NULL,
  available_copies NUMBER(5) DEFAULT 1 NOT NULL,
  CONSTRAINT books_total_copies_ck CHECK (total_copies > 0),
  CONSTRAINT books_available_copies_ck
    CHECK (available_copies >= 0 AND available_copies <= total_copies)
);

CREATE TABLE members (
  member_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(150) NOT NULL,
  email VARCHAR2(254) NOT NULL UNIQUE
);

CREATE TABLE loans (
  loan_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id NUMBER NOT NULL REFERENCES books(book_id),
  member_id NUMBER NOT NULL REFERENCES members(member_id),
  issued_on DATE DEFAULT SYSDATE NOT NULL,
  due_on DATE DEFAULT (SYSDATE + 14) NOT NULL,
  returned_on DATE,
  CONSTRAINT loans_dates_ck CHECK (returned_on IS NULL OR returned_on >= issued_on)
);

CREATE INDEX loans_active_book_idx ON loans(book_id, returned_on);
CREATE INDEX loans_member_idx ON loans(member_id);

CREATE OR REPLACE PACKAGE libraries_api AS
  PROCEDURE add_book(
    p_title IN books.title%TYPE,
    p_author IN books.author%TYPE,
    p_isbn IN books.isbn%TYPE,
    p_copies IN books.total_copies%TYPE
  );
  PROCEDURE add_member(
    p_name IN members.name%TYPE,
    p_email IN members.email%TYPE
  );
  PROCEDURE issue_book(
    p_book_id IN books.book_id%TYPE,
    p_member_id IN members.member_id%TYPE
  );
  PROCEDURE return_book(p_loan_id IN loans.loan_id%TYPE);
END libraries_api;
/

CREATE OR REPLACE PACKAGE BODY libraries_api AS
  PROCEDURE add_book(
    p_title IN books.title%TYPE,
    p_author IN books.author%TYPE,
    p_isbn IN books.isbn%TYPE,
    p_copies IN books.total_copies%TYPE
  ) IS
  BEGIN
    INSERT INTO books (title, author, isbn, total_copies, available_copies)
    VALUES (TRIM(p_title), TRIM(p_author), NULLIF(TRIM(p_isbn), ''), p_copies, p_copies);
  END add_book;

  PROCEDURE add_member(
    p_name IN members.name%TYPE,
    p_email IN members.email%TYPE
  ) IS
  BEGIN
    INSERT INTO members (name, email)
    VALUES (TRIM(p_name), LOWER(TRIM(p_email)));
  END add_member;

  PROCEDURE issue_book(
    p_book_id IN books.book_id%TYPE,
    p_member_id IN members.member_id%TYPE
  ) IS
    v_available books.available_copies%TYPE;
    v_member_id members.member_id%TYPE;
  BEGIN
    BEGIN
      SELECT available_copies
        INTO v_available
        FROM books
       WHERE book_id = p_book_id
         FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20003, 'Book not found.');
    END;

    BEGIN
      SELECT member_id
        INTO v_member_id
        FROM members
       WHERE member_id = p_member_id;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'Member not found.');
    END;

    IF v_available < 1 THEN
      RAISE_APPLICATION_ERROR(-20001, 'No copies of this book are available.');
    END IF;

    INSERT INTO loans (book_id, member_id)
    VALUES (p_book_id, p_member_id);

    UPDATE books
       SET available_copies = available_copies - 1
     WHERE book_id = p_book_id;
  END issue_book;

  PROCEDURE return_book(p_loan_id IN loans.loan_id%TYPE) IS
    v_book_id loans.book_id%TYPE;
  BEGIN
    SELECT book_id
      INTO v_book_id
      FROM loans
     WHERE loan_id = p_loan_id
       AND returned_on IS NULL
       FOR UPDATE;

    UPDATE loans
       SET returned_on = SYSDATE
     WHERE loan_id = p_loan_id;

    UPDATE books
       SET available_copies = available_copies + 1
     WHERE book_id = v_book_id;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20002, 'Loan not found or the book is already returned.');
  END return_book;
END libraries_api;
/

